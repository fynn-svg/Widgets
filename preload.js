const { contextBridge, ipcRenderer, webUtils } = require('electron');
const inv = (c, ...a) => ipcRenderer.invoke(c, ...a);
contextBridge.exposeInMainWorld('api', {
  getCfg: () => inv('cfg:get'),
  tbGet: () => inv('tb:get'), tbRun: (id) => inv('tb:run', id), tbPreview: () => inv('tb:preview'), tbPickApp: () => inv('tb:pickApp'), tbIcon: (p) => inv('tb:icon', p),
  onTb: (fn) => { ipcRenderer.on('tb:update', () => fn('update')); ipcRenderer.on('tb:show', (_e, on) => fn(on ? 'show' : 'hide')); },
  updCheck: () => inv('upd:check'),
  updInfo: () => inv('upd:info'),
  updInstall: () => inv('upd:install'),
  onUpdProgress: (fn) => ipcRenderer.on('upd:progress', (_e, p) => fn(p)),
  onCfg: (fn) => ipcRenderer.on('cfg', (_e, c) => fn(c)),
  onNavigate: (fn) => ipcRenderer.on('navigate', (_e, p) => fn(p)),
  patch: (key, value) => inv('cfg:patch', key, value),
  addWidget: (w) => inv('widget:add', w),
  updateWidget: (id, p) => inv('widget:update', id, p),
  removeWidget: (id) => inv('widget:remove', id),
  duplicateWidget: (id) => inv('widget:duplicate', id),
  saveData: (id, d) => ipcRenderer.send('widget:data', id, d),
  dragBegin: (id, mode) => ipcRenderer.send('drag:begin', id, mode),
  dragMove: () => ipcRenderer.send('drag:move'),
  dragEnd: () => ipcRenderer.send('drag:end'),
  widgetMenu: (id) => ipcRenderer.send('widget:menu', id),
  sys: () => inv('sys:stats'),
  displays: () => inv('displays:get'),
  moveToDisplay: (id, did) => inv('widget:toDisplay', id, did),
  pickFolder: () => inv('pick:folder'),
  listPhotos: (dirs, deep) => inv('photos:list', dirs, deep),
  autostart: (on) => inv('autostart:set', on),
  setAllOnTop: (on) => inv('widgets:allOnTop', on),
  setAllVisible: (on) => inv('widgets:allVisible', on),
  saveLayout: (name) => inv('layout:save', name),
  applyLayout: (name) => inv('layout:apply', name),
  openDataFolder: () => inv('app:openData'),
  resetAll: () => inv('app:reset'),
  icloudConnect: (u, p) => inv('icloud:connect', u, p), icloudSync: () => inv('icloud:sync'), icloudDisconnect: () => inv('icloud:disconnect'),
  icloudToggleTodo: (uid, done) => inv('icloud:toggleTodo', uid, done), icloudCreateTodo: (t, d) => inv('icloud:createTodo', t, d), icloudCreateEvent: (t, s, e) => inv('icloud:createEvent', t, s, e),
  stocks: (s) => inv('net:stocks', s), rss: (u) => inv('net:rss', u), openUrl: (u) => inv('shell:open', u), media: (k) => inv('media:key', k),
  winCtl: (a) => ipcRenderer.send('win:ctl', a), onWinState: (fn) => ipcRenderer.on('win:state', (_e, s) => fn(s)),
  taskAdd: (p) => inv('tasks:add', p), taskDone: (id, d) => inv('tasks:done', id, d), taskUpdate: (id, p) => inv('tasks:update', id, p), taskRemove: (id) => inv('tasks:remove', id), taskClearLog: () => inv('tasks:clearLog'),
  location: (force) => inv('loc:get', !!force),
  onRefresh: (fn) => ipcRenderer.on('refresh', () => fn()), refresh: () => inv('app:refresh'),
  wxGet: (k) => inv('wx:get', k), wxSet: (k, v) => inv('wx:set', k, v), exportCfg: () => inv('cfg:export'), importCfg: () => inv('cfg:import'),
  pickImage: () => inv('pick:image'), saveJson: (n, d) => inv('file:saveJson', n, d), openJson: () => inv('file:openJson'),
  mediaState: (k) => inv('media:state', k),
  dockGet: () => inv('dock:get'), onDockUpdate: (fn) => ipcRenderer.on('dock:update', () => fn()), dockLaunch: (id) => inv('dock:launch', id), dockHover: (b) => ipcRenderer.send('dock:hover', b), dockHidden: (b) => ipcRenderer.send('dock:hidden', b),
  dockReorder: (ids) => inv('dock:reorder', ids), dockRemove: (id) => inv('dock:remove', id), dockAddPath: (p, n) => inv('dock:addPath', p, n), dockPickApp: () => inv('dock:pickApp'), dockScanApps: () => inv('dock:scanApps'), dockItemMenu: (id) => ipcRenderer.send('dock:itemMenu', id),
  pathOf: (file) => { try { return webUtils.getPathForFile(file); } catch { return ''; } }, wallpaperColors: () => inv('wallpaper:colors'),
  perf: () => inv('perf:get'), clipGet: () => inv('clip:get'), clipCopy: (t) => inv('clip:copy', t), clipRemove: (t) => inv('clip:remove', t), clipClear: () => inv('clip:clear'),
  qs: (n, a) => inv('qs:action', n, a), focusSet: (on, id, dock) => inv('focus:set', on, id, dock), batteryDevices: () => inv('battery:devices'), photoAlbums: (d) => inv('photos:albums', d),
  eventAdd: (e) => inv('events:add', e), eventRemove: (id) => inv('events:remove', id),
  openApp: (page) => inv('app:open', page),
  gcalSet: (u) => inv('gcal:set', u), gcalSync: () => inv('gcal:sync'), gcalOpen: () => inv('gcal:open'), fySys: () => inv('fy:sysinfo'),
  temp: () => inv('temp:get'), screentime: () => inv('screentime:get'),
});
